-- Pantavion Water PostGIS + MVT foundation
-- Canonical rule: the authentic source/master stays immutable.
-- These tables contain web-optimized derived GIS objects only.

create extension if not exists postgis with schema extensions;

create table if not exists public.water_gis_import_jobs (
  job_id uuid primary key default gen_random_uuid(),
  source_id uuid null references public.water_map_ingest_catalog(source_id) on delete restrict,
  map_id text not null,
  source_format text not null,
  source_sha256 text null,
  source_storage_bucket text null,
  source_storage_path text null,
  pipeline_id text not null default 'pantavion-gis-importer',
  pipeline_version text not null default 'v1',
  status text not null default 'queued',
  detected_crs text null,
  output_crs text not null default 'EPSG:4326',
  feature_count bigint not null default 0,
  invalid_geometry_count bigint not null default 0,
  topology_state text not null default 'pending',
  tile_state text not null default 'pending',
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  started_at timestamptz null,
  completed_at timestamptz null,
  updated_at timestamptz not null default now(),
  constraint water_gis_import_jobs_status_check
    check (status in ('queued','processing','review_required','ready','failed')),
  constraint water_gis_import_jobs_map_id_check
    check (length(trim(map_id)) > 0)
);

create table if not exists public.water_gis_features (
  feature_id bigint generated by default as identity primary key,
  import_job_id uuid null references public.water_gis_import_jobs(job_id) on delete restrict,
  map_id text not null,
  source_kind text not null,
  source_table text null,
  source_feature_id text not null,
  source_sha256 text null,
  object_class text not null default 'network-object',
  layer_name text null,
  name text null,
  style_url text null,
  properties jsonb not null default '{}'::jsonb,
  geom extensions.geometry(Geometry, 4326) not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (map_id, source_kind, source_feature_id)
);

create index if not exists water_gis_features_geom_gist
  on public.water_gis_features using gist (geom);
create index if not exists water_gis_features_map_id_feature_id_idx
  on public.water_gis_features (map_id, feature_id);
create index if not exists water_gis_features_object_class_idx
  on public.water_gis_features (map_id, object_class);
create index if not exists water_gis_features_layer_name_idx
  on public.water_gis_features (map_id, layer_name);
create index if not exists water_gis_features_import_job_id_idx
  on public.water_gis_features (import_job_id);
create index if not exists water_gis_import_jobs_source_id_idx
  on public.water_gis_import_jobs (source_id);

create table if not exists public.water_network_nodes (
  node_id bigint generated by default as identity primary key,
  map_id text not null,
  node_key text not null,
  node_class text not null default 'junction',
  geom extensions.geometry(Point, 4326) not null,
  properties jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (map_id, node_key)
);

create index if not exists water_network_nodes_geom_gist
  on public.water_network_nodes using gist (geom);

create table if not exists public.water_network_edges (
  edge_id bigint generated by default as identity primary key,
  map_id text not null,
  feature_id bigint not null references public.water_gis_features(feature_id) on delete restrict,
  from_node_id bigint null references public.water_network_nodes(node_id) on delete restrict,
  to_node_id bigint null references public.water_network_nodes(node_id) on delete restrict,
  edge_class text not null default 'pipe',
  connectivity_state text not null default 'unresolved',
  properties jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (map_id, feature_id)
);

create index if not exists water_network_edges_from_node_idx
  on public.water_network_edges (map_id, from_node_id);
create index if not exists water_network_edges_to_node_idx
  on public.water_network_edges (map_id, to_node_id);
create index if not exists water_network_edges_feature_id_idx
  on public.water_network_edges (feature_id);
create index if not exists water_network_edges_from_node_id_idx
  on public.water_network_edges (from_node_id);
create index if not exists water_network_edges_to_node_id_idx
  on public.water_network_edges (to_node_id);

