import assert from "node:assert/strict";
import { drawingGeometry, patchDrawing, drawWaterAnnotation } from "../core/infrastructure/water/water-map-drawing.ts";

const cad = "canonical-2026-andreaspap";
const style = { color: "#22d3ee", width: 3, dashed: false, text: "SV 12", symbol: "valve" };
const polygon = drawingGeometry("polygon", [[5, 5], [15, 5], [15, 20]], cad);
assert.equal(polygon.crs.authority, "LOCAL");
assert.equal(polygon.crs.code, cad);
assert.deepEqual(polygon.coordinates[0].at(-1), [5, 5]);
assert.throws(() => drawingGeometry("polygon", [[0, 0], [0, 0], [1, 1]], cad));
assert.throws(() => drawingGeometry("line", [[1, 1], [1, 1]], null));
assert.throws(() => drawingGeometry("text", [[200, 90]], null));
assert.throws(() => drawingGeometry("line", [[0, 0], [NaN, 3]], cad));
const point = drawingGeometry("symbol", [[33.04, 34.68]], null);
assert.deepEqual(point.crs, { authority: "EPSG", code: "4326" });
const row = { patch_id: "p1", status: "pending_review", geometry: polygon, attributes: { drawing: { tool: "polygon", style } } };
assert.equal(patchDrawing(row, null), null, "Unaligned CAD must never appear at geographic positions");
assert.equal(patchDrawing(row, "legacy-george-85m"), null, "Different CAD sources must remain separate");
assert.equal(patchDrawing(row, cad)?.id, "p1", "B and D can show the same source-bound patch");
assert.equal(patchDrawing({ ...row, geometry: { ...polygon, coordinates: [[[]]] } }, cad), null);
const calls = [];
const ctx = new Proxy({}, { get: (_, key) => (...args) => calls.push([key, ...args]), set: () => true });
const arrow = { id: "draft", tool: "arrow", points: [[0, 0], [10, 20]], style, status: "pending_review" };
drawWaterAnnotation(ctx, arrow, ([x, y]) => [x * 2, y * 3]);
assert(calls.some(([key, x, y]) => key === "lineTo" && x === 20 && y === 60), "Rendering projects the actual selected point");
assert(calls.some(([key, text]) => key === "fillText" && text === "Προς έγκριση"));
assert.equal(calls[0][0], "save");
assert.equal(calls.at(-1)[0], "restore");
console.log("Water drawing: geometry, source isolation, round-trip and projected rendering passed");
