export function getSupportedPantavionLanguage(code: string | null | undefined) {
  if (!code) return null;

  return PANTAVION_LANGUAGE_CATALOG.find((language) => language.code === code) ?? null;
}

export function getPantavionUiLanguage(code: string | null | undefined): PantavionUiLanguage {
  return code === "el" ? "el" : "en";
}

export function getPantavionLanguageLabel(code: string | null | undefined) {
  return getSupportedPantavionLanguage(code)?.name ?? "Greek / Ελληνικά";
}
